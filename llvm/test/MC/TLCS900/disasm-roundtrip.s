;
; Disassembler round-trip test: verify that assembling instructions,
; then reassembling the canonical output, produces identical text
; and encodings. The first pass (hand-written -> canonical) may
; differ cosmetically, so we compare pass 1 output with pass 2.
;
; This test covers all major TLCS-900 instruction categories:
;   - Single-byte system instructions
;   - Flag manipulation
;   - EI/DI interrupt control
;   - SWI software interrupts
;   - RETD (return + deallocate)
;   - 32-bit PUSH/POP
;   - 16-bit PUSHW/POPW (compact)
;   - 16-bit PUSH/POP (prefix)
;   - 8-bit PUSH/POP
;   - LD immediate (8/16/32-bit)
;   - Compact LD (ldb/ldw)
;   - Register-register ALU (8/16/32-bit)
;   - Register-immediate ALU (8/16/32-bit)
;   - INC/DEC (8/16/32-bit)
;   - Shifts and rotates (8/16/32-bit)
;   - Bit manipulation (8/16-bit)
;   - Unary operations (NEG, CPL, EXTS, EXTZ)
;   - Memory load/store (register-indirect, d8 displacement)
;   - Memory ALU operations
;   - LDA (load effective address)
;   - 8-bit and 16-bit memory load/store
;   - Block transfers (LDI/LDIR/LDD/LDDR)
;   - Block compares (CPI/CPIR/CPD/CPDR)
;   - Branches (JP, JR, JRL, conditional)
;   - CALL/CALR (direct and indirect)
;   - Conditional RET
;   - DJNZ (8/16-bit)
;   - MUL/MULS/DIV/DIVS
;   - Direct memory addressing (E1/F1 prefix, 16-bit addr)
;   - EX (8/16-bit register exchange)
;   - SCC (set on condition, 8-bit)
;   - Compact LD/CP (lds8/cps)
;   - I/O instructions (LDIO/LDWIO)
;   - PUSHW immediate

