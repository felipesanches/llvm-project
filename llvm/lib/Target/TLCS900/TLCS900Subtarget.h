#ifndef LLVM_LIB_TARGET_TLCS900_TLCS900SUBTARGET_H
#define LLVM_LIB_TARGET_TLCS900_TLCS900SUBTARGET_H

#include "TLCS900FrameLowering.h"
#include "TLCS900ISelLowering.h"
#include "TLCS900InstrInfo.h"
#include "llvm/CodeGen/SelectionDAGTargetInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"

#define GET_SUBTARGETINFO_HEADER
#include "TLCS900GenSubtargetInfo.inc"

namespace llvm {
class TLCS900Subtarget : public TLCS900GenSubtargetInfo {
protected:
  // Subtarget feature flags — set by ParseSubtargetFeatures (auto-generated).
  bool HasHWMul = false;
  bool HasMinMax = false;
  bool HasMDMA = false;

  SelectionDAGTargetInfo TSInfo;
  TLCS900InstrInfo InstrInfo;
  TLCS900FrameLowering FrameLowering;
  TLCS900TargetLowering TLInfo;
  TLCS900RegisterInfo RegInfo;

public:
  /// This constructor initializes the data members to match that
  /// of the specified triple.
  TLCS900Subtarget(const Triple &TT, StringRef CPU, StringRef FS,
                const TargetMachine &TM);

  /// ParseSubtargetFeatures - Parses features string setting specified
  /// subtarget options.  Definition of function is auto generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  TLCS900Subtarget &initializeSubtargetDependencies(const Triple &TT,
                                                  StringRef CPU, StringRef FS,
                                                  const TargetMachine &TM);

  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }

  const TLCS900InstrInfo *getInstrInfo() const override {
    return &InstrInfo;
  }

  const TargetFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }

  const TLCS900RegisterInfo *getRegisterInfo() const override {
    return &RegInfo;
  }

  const TLCS900TargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }

  /// getMaxInlineSizeThreshold - Returns the maximum memset / memcpy size
  /// that still makes it profitable to inline the call.
  unsigned getMaxInlineSizeThreshold() const {
    return 64;
  }

  // Feature queries.
  bool hasHWMul() const { return HasHWMul; }
  bool hasMinMax() const { return HasMinMax; }
  bool hasMDMA() const { return HasMDMA; }
};
}

#endif // end LLVM_LIB_TARGET_TLCS900_TLCS900SUBTARGET_H
